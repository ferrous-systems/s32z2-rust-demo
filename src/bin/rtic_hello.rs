//! RTIC hello-world for NXP S32Z2

#![no_std]
#![no_main]

#[rtic::app(device=s32z2_rust_demo)]
mod app {
    use arm_dcc::dprintln as println;
    use fugit::ExtU64;
    use rtic_time::Monotonic;
    use s32z2_rust_demo::{Interrupt, Mono};

    #[shared]
    struct SharedResources {}

    #[local]
    struct LocalResources {}

    #[init]
    fn init(mut ctx: init::Context) -> (SharedResources, LocalResources) {
        println!("In init...");

        // TODO: have RTIC configure the GIC with all the desired interrupts at the desired priorities
        ctx.core
            .gic
            .set_interrupt_priority(Interrupt::VirtTimer.as_intid(), 0x31);
        ctx.core
            .gic
            .enable_interrupt(Interrupt::VirtTimer.as_intid(), true);

        // TODO: have RTIC set the primask for us
        rtic::export::Gic::set_priority_mask(0xFF);

        Mono::start(ctx.core.virt_timer);

        loop_1000::spawn().unwrap();
        loop_4000::spawn().unwrap();

        (SharedResources {}, LocalResources {})
    }

    #[task]
    async fn loop_1000(_ctx: loop_1000::Context) -> ! {
        let mut tick_at = Mono::now();
        loop {
            println!(
                "+++ 1000 ms tick @ {} ms",
                Mono::now().duration_since_epoch().to_millis()
            );
            tick_at += 1000.millis();
            Mono::delay_until(tick_at).await;
        }
    }

    #[task]
    async fn loop_4000(_ctx: loop_4000::Context) -> ! {
        let mut tick_at = Mono::now();
        loop {
            println!(
                "***** 4000 ms tick @ {} ms",
                Mono::now().duration_since_epoch().to_millis()
            );
            tick_at += 4000.millis();
            Mono::delay_until(tick_at).await;
        }
    }

    // TODO: have RTIC generate this routine for us (or #[derive] it from the interrupt enum)
    #[aarch32_rt::irq]
    fn irq() {
        unsafe {
            rtic::export::get_and_process(|int_id| {
                let interrupt: Interrupt = int_id.into();
                match interrupt {
                    Interrupt::VirtTimer => {
                        Mono::handle_irq();
                    }
                    _ => {
                        unimplemented!();
                    }
                }
            });
        }
    }

    /// The entry-point to the Rust application.
    #[aarch32_rt::entry]
    fn main() -> ! {
        s32z2_rust_demo::setup_core();
        println!("In entry point");
        unsafe {
            // this is the function generated by rtic
            main();
        }
    }
}
